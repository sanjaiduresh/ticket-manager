async function fixture(page: Page, role: Role = 'technician') {
  await page.clock.setFixedTime(new Date('2026-10-20T12:00:00Z'))
  const data = await createDemoApi().load()
  const actor = data.profiles.find(p => p.role === role)!
  if (role === 'technician') data.tickets = data.tickets.filter(ticket => [ticket.assigned_to].flat().includes(actor.id))
  const ticket = data.tickets[0]
  const records: AttendanceRecord[] = [{ id: 'mine', company_id: actor.company_id, employee_id: role === 'technician' ? actor.id : 'demo-tech-1', day: '2026-10-20', status: 'present', check_in: '2026-10-20T03:30:00.000Z', check_out: null, note: 'Morning register', version: 1, recorded_by: 'demo-owner', updated_by: 'demo-owner', updated_at: '2026-10-20T04:00:00.000Z' }]
  const items: AssignmentNotification[] = [{ id: 'first', company_id: actor.company_id, recipient_id: actor.id, ticket_id: ticket.id, ticket_number: ticket.number, kind: 'created', created_at: new Date().toISOString(), read_at: null }]
  let attendanceFailure = 0, notificationFailure = 0
  let saveFailure: { status: number; error: string } | null = null
  const attendanceQueries: URL[] = []
  const attendanceWrites: AttendanceInput[] = []
  await page.addInitScript(() => localStorage.setItem('dsa-session-present', 'true'))
  await page.route('**/*', async route => {
    const url = new URL(route.request().url())
    if (!['localhost', '127.0.0.1'].includes(url.hostname)) return route.abort()
    if (!url.pathname.startsWith('/api/')) return route.continue()
    const reply = (body: unknown, status = 200) => route.fulfill({ status, contentType: 'application/json', body: JSON.stringify(body) })
    if (url.pathname === '/api/auth/session') return reply({ user: { id: actor.id, email: 'fake@example.test' } })
    if (url.pathname === '/api/profile') return reply(actor)
    if (url.pathname === '/api/workspace') return reply(data)
    if (url.pathname === '/api/attendance') {
      if (route.request().method() === 'POST') {
        const input = route.request().postDataJSON() as AttendanceInput
        attendanceWrites.push(input)
        if (role === 'technician') return reply({ error: 'Office or owner access required' }, 403)
        if (saveFailure) return reply({ error: saveFailure.error }, saveFailure.status)
        const prior = records.find(record => record.id === input.id)
        if (prior && prior.version !== input.version) return reply({ error: 'Attendance changed. Reload the record before saving' }, 409)
        if (!prior && records.some(record => record.employee_id === input.employee_id && record.day === input.day)) return reply({ error: 'Attendance already exists for this employee and day. Edit the existing record' }, 409)
        const next: AttendanceRecord = { ...input, company_id: actor.company_id, version: input.version + 1, recorded_by: prior ? prior.recorded_by : actor.id, updated_by: actor.id, updated_at: '2026-10-20T12:00:00.000Z' }
        if (prior) Object.assign(prior, next)
        else records.push(next)
        return reply({ ok: true })
      }
      attendanceQueries.push(url)
      return attendanceFailure ? reply({ error: 'Attendance access denied' }, attendanceFailure) : reply({ from: url.searchParams.get('from'), to: url.searchParams.get('to'), generated_at: new Date().toISOString(), records: records.filter(record => (role !== 'technician' || record.employee_id === actor.id) && record.day >= url.searchParams.get('from')! && record.day <= url.searchParams.get('to')!) })
    }
    if (url.pathname === '/api/notifications') return notificationFailure ? reply({ error: 'Inbox access denied' }, notificationFailure) : reply({ items, unread_count: items.filter(item => !item.read_at).length })
    if (url.pathname === '/api/notifications/read') {
      const { id } = route.request().postDataJSON()
      items.filter(item => !id || item.id === id).forEach(item => { item.read_at = new Date().toISOString() })
      return reply({ ok: true })
    }
    if (url.pathname.endsWith('/events') || url.pathname.endsWith('/images')) return reply([])
    throw new Error(`Unexpected API request: ${url.pathname}`)
  })
  return { actor, ticket, records, attendanceQueries, attendanceWrites, rejectSave: (status: number, error: string) => { saveFailure = { status, error } }, denyAttendance: () => { attendanceFailure = 403 }, allowAttendance: () => { attendanceFailure = 0 }, denyNotifications: () => { notificationFailure = 403 }, addNotification: () => { items.unshift({ ...items[0], id: `next-${items.length}`, kind: 'assigned', read_at: null }) } }
}

